import os
stats = {}
for name, pub_prefix, old_sum, d, idx, new_sum in CONV:
    f = f"data/direction_signals/{name}.json"
    sig = json.load(open(f, encoding="utf-8"))
    changed = False
    for s in sig["signals"]:
        if s.get("cat") == "无预测周期" and s["pub"].startswith(pub_prefix) and s["summary"] == old_sum:
            s["cat"] = "scored"
            s["spec"] = "t5"
            s["s"] = 1
            s["d"] = d
            s["idx"] = idx
            s["summary"] = new_sum
            changed = True
            stats[name] = stats.get(name, 0) + 1
    if changed:
        sig["signals"].sort(key=lambda s: s["pub"])
        json.dump(sig, open(f, "w", encoding="utf-8"), ensure_ascii=False, indent=1)
        print(f"{name}: {stats[name]} 条转 t5")
print("完成，共转换", sum(stats.values()), "条")
